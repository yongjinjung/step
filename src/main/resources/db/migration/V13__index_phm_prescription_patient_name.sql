-- =====================================================================
-- V13: 처방 환자명 인덱스
-- ---------------------------------------------------------------------
-- 약제 목록 검색어는 처방전번호 OR 환자번호 OR 환자명 앞부분 일치(키워드%)다.
-- OR 조건은 모든 조건이 인덱스를 쓸 수 있어야 인덱스(index merge)를 탄다. 처방전번호(uk_phm_prescription_no)와
-- 환자번호(ix_phm_prescription_patient)에는 이미 인덱스가 있어 환자명 인덱스를 더한다.
--
-- 주의: 이 파일은 Oracle 21c와 테스트용 H2(MODE=Oracle) 양쪽에서 실행된다.
-- =====================================================================
CREATE INDEX ix_phm_prescription_patient_name ON phm_prescription (patient_name);
