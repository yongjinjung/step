-- =====================================================================
-- V8: 공통 코드 (com_code_group, com_code_value) + 컬럼 정의의 코드 그룹 매핑
-- ---------------------------------------------------------------------
-- 공통 코드는 코드 그룹(코드ID) 하나에 코드값 여러 개가 속하는 2단 구조다.
--   예) ORDER_STAT(주문상태) → 01 접수, 02 결제완료, 03 배송중
-- 코드성 컬럼(예: TB_ORDER.ORDER_STAT_CD)은 meta_column.code_group_id로 코드 그룹에 매핑한다.
--
-- 코드ID와 코드값은 대문자로 정규화해 저장한다. Oracle은 문자열 비교에서 대소문자를 구분하므로,
-- 정규화하지 않으면 cust와 CUST가 서로 다른 값으로 들어간다.
-- =====================================================================
CREATE TABLE com_code_group (
    -- 코드 그룹 ID (자동 증가 기본키). 컬럼 매핑은 이 값으로 연결하므로 코드ID를 바꿔도 매핑이 유지된다.
    id          NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 코드ID. 대문자로 정규화해 저장하며 전체에서 유일하다.
    -- 영문자로 시작하는 영문/숫자/'_', 50자 이하. 예) ORDER_STAT
    code_id     VARCHAR2(50 CHAR)   NOT NULL,
    -- 코드명. 예) 주문상태
    code_name   VARCHAR2(200 CHAR)  NOT NULL,
    -- 설명 (선택)
    description VARCHAR2(1000 CHAR),
    -- 사용 여부 'Y'/'N'. 미사용 그룹은 컬럼에 새로 매핑할 수 없다 (기존 매핑은 유지)
    used_yn     CHAR(1)       NOT NULL,
    -- 생성 일시 (애플리케이션이 저장 시 채운다)
    created_at  TIMESTAMP(6)   NOT NULL,
    -- 최종 수정 일시 (애플리케이션이 저장 시 채운다)
    updated_at  TIMESTAMP(6)   NOT NULL,
    PRIMARY KEY (id),
    -- 코드ID 유일 제약 (409 DUPLICATE_CODE_ID)
    CONSTRAINT uk_com_code_group_code_id UNIQUE (code_id)
);

CREATE TABLE com_code_value (
    -- 코드값 ID (자동 증가 기본키)
    id          NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 소속 코드 그룹 ID (com_code_group.id). 그룹을 삭제하면 서비스가 코드값을 먼저 삭제한다.
    group_id    NUMBER(19)        NOT NULL,
    -- 코드값. 대문자로 정규화해 저장하며 그룹 안에서 유일하다.
    -- 영문/숫자/'_'/'-', 50자 이하. 예) 01, Y, ACTIVE
    code_value  VARCHAR2(50 CHAR)   NOT NULL,
    -- 코드값명. 예) 접수
    value_name  VARCHAR2(200 CHAR)  NOT NULL,
    -- 설명 (선택)
    description VARCHAR2(1000 CHAR),
    -- 그룹 내 정렬 순서 (1 이상). 유일하지 않으며 같으면 id 순으로 정렬한다.
    sort_order  NUMBER(10)           NOT NULL,
    -- 사용 여부 'Y'/'N'. 코드값 목록에는 미사용 값도 함께 나온다 (화면에서 구분)
    used_yn     CHAR(1)       NOT NULL,
    -- 생성 일시 (애플리케이션이 저장 시 채운다)
    created_at  TIMESTAMP(6)   NOT NULL,
    -- 최종 수정 일시 (애플리케이션이 저장 시 채운다)
    updated_at  TIMESTAMP(6)   NOT NULL,
    PRIMARY KEY (id),
    -- 그룹 내 코드값 유일 제약 (409 DUPLICATE_CODE_VALUE)
    CONSTRAINT uk_com_code_value_group_value UNIQUE (group_id, code_value),
    -- 코드 그룹 참조
    CONSTRAINT fk_com_code_value_group FOREIGN KEY (group_id) REFERENCES com_code_group (id)
);

-- 컬럼 정의의 공통 코드 매핑. 선택이며 NULL이면 매핑 없음.
-- 비표준 검출 대상이 아니다 (용어 매핑과 별개의 정보).
ALTER TABLE meta_column ADD (code_group_id NUMBER(19));
-- 코드 그룹 참조. 컬럼에 매핑된 코드 그룹은 서비스에서 먼저 막아 409(CODE_GROUP_IN_USE)로 응답한다.
ALTER TABLE meta_column ADD CONSTRAINT fk_meta_column_code_group
    FOREIGN KEY (code_group_id) REFERENCES com_code_group (id);
